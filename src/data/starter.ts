const seededAt = Date.UTC(2026, 8, 15, 12, 0, 0);

export function createStarterPeople(): Person[] {
  const live = STARTER_PROFILES.map((snap, i) =>
    personFromSnapshot(snap, {
      tags: i >= 5 ? ["見本", "AI"] : ["見本"],
      note: "",
      addedAt: seededAt - i * 60_000,
      source: "starter",
      lastCheckedAt: seededAt,
    }),
  );
  const demo = DEMO_EXAMPLES.map((row, i) =>
    personFromSnapshot(row.snap, {
      tags: ["見本"],
      note: row.note,
      addedAt: seededAt - (STARTER_PROFILES.length + i) * 60_000,
      source: "starter",
      followsYou: row.followsYou,
      lastCheckedAt: seededAt,
    }),
  );
  return [...live, ...demo];
}
